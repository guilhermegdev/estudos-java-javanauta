package fundamentos.revisao;

public class ExercicioExpressoesComparativas {
    public static void main(String[] args) {

        int filtrosNoEstoque = 5;

        System.out.println(filtrosNoEstoque == 5); // == (Igual)
        System.out.println(filtrosNoEstoque != 3); // != (Diferente de)
        System.out.println(filtrosNoEstoque > 5); // > (Maior que)
        System.out.println(filtrosNoEstoque < 5); // < (Menor que)
        System.out.println(filtrosNoEstoque <= 5); // <= (Menor ou igual)
        System.out.println(filtrosNoEstoque >= 5); // >= (Maior ou igual)
    }
}
